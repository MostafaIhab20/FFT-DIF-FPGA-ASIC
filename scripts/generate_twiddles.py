#!/usr/bin/env python3
# =============================================================================
# File Name      : generate_twiddles.py
# Author         : Mostafa Ihab
# Creation Date  : 2026-09-28
# Version        : 2.0
# Description    : Automatic Twiddle Factor Generator for Parameterized R2SDF FFT.
#                  Generates a clean, self-contained SystemVerilog ROM module
#                  (twiddle_rom.sv) using combinational 'case' lookup (ideal for
#                  both ASIC logic synthesis and FPGA block/distributed ROM inference).
#                  Supports arbitrary power-of-2 FFT points (N in 8, 16, 32, 64, 128, ...).
# =============================================================================

import argparse
import math
import os
import sys
from datetime import date

def generate_twiddle_rom(n_points, author="Mostafa Ihab", sv_out_path="DESIGN/RTL/twiddle_rom.sv"):
    if n_points < 4 or (n_points & (n_points - 1)) != 0:
        raise ValueError(f"FFT points N must be a power of 2 >= 4, got {n_points}")

    num_twiddles = n_points // 2
    addr_width = max(1, int(math.ceil(math.log2(num_twiddles))))
    neg_j_addr = n_points // 4

    print(f"\n=========================================================================")
    print(f"   TWIDDLE FACTOR GENERATOR: {n_points}-Point Radix-2 DIF FFT")
    print(f"=========================================================================")
    print(f"  FFT Points (N)     : {n_points}")
    print(f"  Twiddle Entries    : {num_twiddles} entries (k = 0 .. {num_twiddles - 1})")
    print(f"  Address Width      : {addr_width} bits")
    print(f"  Unity (W^0 = 1)    : addr = 0")
    print(f"  Neg-J (W^{neg_j_addr} = -j) : addr = {neg_j_addr}")
    print(f"  Output Format      : 16-bit Signed Fixed-Point Q1.15")
    print(f"  Target File        : {sv_out_path}")

    twiddles = []
    for k in range(num_twiddles):
        theta = -2.0 * math.pi * k / n_points
        re = math.cos(theta)
        im = math.sin(theta)

        # Quantize to 16-bit signed Q1.15
        if k == 0:
            q_re = 32767
            q_im = 0
        elif k == neg_j_addr:
            q_re = 0
            q_im = -32768
        else:
            q_re = int(round(re * 32768.0))
            q_im = int(round(im * 32768.0))
            q_re = max(-32768, min(32767, q_re))
            q_im = max(-32768, min(32767, q_im))

        re_disp = 0.0 if abs(re) < 1e-9 else re
        im_disp = 0.0 if abs(im) < 1e-9 else im

        h_re = f"{(q_re & 0xFFFF):04X}"
        h_im = f"{(q_im & 0xFFFF):04X}"
        twiddles.append({
            "k": k,
            "re_float": re_disp,
            "im_float": im_disp,
            "re_hex": h_re,
            "im_hex": h_im
        })

    os.makedirs(os.path.dirname(os.path.abspath(sv_out_path)), exist_ok=True)
    today = date.today().isoformat()

    sv_lines = [
        "// =============================================================================",
        f"// File Name      : {os.path.basename(sv_out_path)}",
        f"// Author         : {author}",
        f"// Creation Date  : {today}",
        "// Version        : 2.0",
        f"// Description    : {num_twiddles}-entry combinational Twiddle Factor ROM storing W_{n_points}^k",
        "//                  in 16-bit signed Q1.15 fixed-point format.",
        "//                  Auto-generated by scripts/generate_twiddles.py.",
        "//                  Includes zero-power hardware bypass flags (is_unity, is_neg_j).",
        "// =============================================================================",
        "",
        "import fft_pkg::*;",
        "",
        "module twiddle_rom #(",
        f"    parameter int N          = {n_points},",
        f"    parameter int ADDR_WIDTH = {addr_width}",
        ")(",
        "    input  logic [ADDR_WIDTH-1:0] addr,",
        "    output complex_t              twiddle,",
        "    output logic                  is_unity,",
        "    output logic                  is_neg_j",
        ");",
        "",
        f"    assign is_unity = (addr == '0);",
        f"    assign is_neg_j = (addr == {addr_width}'d{neg_j_addr});",
        "",
        "    always @* begin",
        "        case (addr)"
    ]

    for item in twiddles:
        k = item["k"]
        h_re = item["re_hex"]
        h_im = item["im_hex"]
        rf = item["re_float"]
        imf = item["im_float"]
        sv_lines.append(
            f"            {addr_width}'d{k}: begin twiddle.re = 16'sh{h_re}; twiddle.im = 16'sh{h_im}; end "
            f"// W{n_points}^{k}: cos={rf:7.4f}, sin={imf:7.4f}"
        )

    sv_lines.append(f"            default: begin twiddle.re = 16'sh7FFF; twiddle.im = 16'sh0000; end")
    sv_lines.append("        endcase")
    sv_lines.append("    end")
    sv_lines.append("")
    sv_lines.append("endmodule : twiddle_rom")
    sv_lines.append("")

    with open(sv_out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(sv_lines))

    print(f"  [SAVED] SystemVerilog ROM : {sv_out_path}")
    print("=========================================================================\n")

def main():
    parser = argparse.ArgumentParser(description="Generate clean Twiddle ROM for Parameterized R2SDF FFT cores.")
    parser.add_argument("-N", "--points", type=int, default=32, help="FFT points (power of 2, default: 32)")
    parser.add_argument("--author", type=str, default="Mostafa Ihab", help="Author name for header")
    parser.add_argument("--sv-out", type=str, default="DESIGN/RTL/twiddle_rom.sv", help="Output SystemVerilog path")

    args = parser.parse_args()
    generate_twiddle_rom(n_points=args.points, author=args.author, sv_out_path=args.sv_out)

if __name__ == "__main__":
    main()
